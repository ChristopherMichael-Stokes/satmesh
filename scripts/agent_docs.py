"""Validate the agent-docs headers and keep `agent-docs/INDEX.md` in step with them.

Every doc in `agent-docs/` opens with a front-matter block of four one-line keys:

    ---
    status: current | historical | superseded by FILE.md
    topic: one of TOPICS
    summary: one line on what the doc holds and concludes
    answers: questions the doc answers, separated by semicolons
    ---

`check` fails when a header is missing or malformed, a superseding doc does not exist, or
`INDEX.md` differs from what `index` would write. `index` rewrites `INDEX.md` from the headers.
"""

import argparse
import re
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import NamedTuple

DOCS_DIR = Path(__file__).resolve().parent.parent / "agent-docs"
INDEX_NAME = "INDEX.md"
KEYS = ("status", "topic", "summary", "answers")
TOPIC_TITLES = {
    "process": "Process, state and decisions",
    "sources": "Imagery and elevation sources",
    "baseline-pipeline": "Baseline pipeline: build, store, exports",
    "evaluation": "Evaluation harness",
    "position-correction": "Imagery position correction",
    "surface-refinement": "Surface refinement and steep faces",
    "height-refinement": "Height refinement and ML",
}
STATUS_ORDER = {"current": 0, "historical": 1, "superseded": 2}
SUPERSEDED = re.compile(r"superseded by (\S+\.md)")
FRONT_MATTER = re.compile(r"\A---\n(.*?)\n---\n", re.DOTALL)
START_HERE = (
    ("status.md", "Current state, what is held, what awaits the owner"),
    ("decisions.md", "Decision log with reasons, by topic"),
    ("risks.md", "Open risks and known limits"),
    ("plan-codes.md", "What the plan codes (E4, F5b, M-A) mean and where each is documented"),
)


class Header(NamedTuple):
    """The parsed front matter of one doc."""

    name: str
    status: str
    topic: str
    summary: str
    answers: str


def parse_header(path: Path) -> tuple[Header | None, list[str]]:
    """Return the header of `path` and the problems found in it."""
    match = FRONT_MATTER.match(path.read_text())
    if match is None:
        return None, [f"{path.name}: no front-matter header"]
    fields = dict(line.split(": ", 1) for line in match.group(1).splitlines() if ": " in line)
    problems = [f"{path.name}: header lacks `{key}`" for key in KEYS if not fields.get(key)]
    if problems:
        return None, problems
    topic = fields["topic"]
    if topic not in TOPIC_TITLES:
        problems.append(f"{path.name}: unknown topic `{topic}`")
    status = fields["status"]
    target = SUPERSEDED.fullmatch(status)
    if status not in ("current", "historical") and target is None:
        problems.append(
            f"{path.name}: status `{status}` is not current, historical or superseded by FILE.md"
        )
    if target is not None and not (DOCS_DIR / target.group(1)).exists():
        problems.append(f"{path.name}: superseding doc `{target.group(1)}` does not exist")
    header = Header(path.name, status, topic, fields["summary"], fields["answers"])
    return header, problems


def collect() -> tuple[list[Header], list[str]]:
    """Read every doc's header; return them with all problems."""
    headers: list[Header] = []
    problems: list[str] = []
    for path in sorted(DOCS_DIR.glob("*.md")):
        if path.name == INDEX_NAME:
            continue
        header, found = parse_header(path)
        problems += found
        if header is not None:
            headers.append(header)
    return headers, problems


def render_index(headers: Sequence[Header]) -> str:
    """Return the text of `INDEX.md` for `headers`."""
    lines = [
        "# Agent docs index",
        "",
        "Generated by `make docs-index` from each doc's header; do not edit by hand. Find a doc",
        "here, read its header (the first lines), then open only the section you need. Statuses:",
        "`current` describes live state or an open plan, `historical` is a finished record that",
        "stays true, `superseded by X` is replaced by X. A new or changed doc gets its header in",
        "the same change, then `make docs-index`.",
        "",
        "## Start here",
        "",
        "| Doc | What it holds |",
        "| --- | --- |",
        *[f"| [{name}]({name}) | {text} |" for name, text in START_HERE],
    ]
    for topic, title in TOPIC_TITLES.items():
        members = [h for h in headers if h.topic == topic]
        if not members:
            continue
        members.sort(key=lambda h: (STATUS_ORDER[h.status.split()[0]], h.name))
        lines += [
            "",
            f"## {title}",
            "",
            "| Doc | Status | Summary | Answers |",
            "| --- | --- | --- | --- |",
        ]
        lines += [
            f"| [{h.name}]({h.name}) | {h.status} | {h.summary} | {h.answers} |" for h in members
        ]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str]) -> int:
    """Run `check` or `index`; return the exit code."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("command", choices=("check", "index"))
    command = parser.parse_args(argv).command
    headers, problems = collect()
    index = DOCS_DIR / INDEX_NAME
    text = render_index(headers)
    if command == "index":
        index.write_text(text)
        for problem in problems:
            sys.stderr.write(problem + "\n")
        return 1 if problems else 0
    if not index.exists() or index.read_text() != text:
        problems.append(f"{INDEX_NAME} is out of date: run `make docs-index`")
    for problem in problems:
        sys.stderr.write(problem + "\n")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
